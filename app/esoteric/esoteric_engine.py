class NeamaEsotericEngine:
    """
    المحرك المعرفي المتخصص في استدعاء وتحليل الطب الروحاني والتراث الفلسفي النوراني بأعلى معايير الأمان والتحليل الأكاديمي.
    """
    def __init__(self):
        self.treatises = ESOTERIC_SPIRITUAL_TREATISES
        self.planes_atlas = UNIVERSAL_PLANES_ATLAS
        self.healers = SPIRITUAL_HEALERS_ENCYCLOPEDIA

    def query_spiritual_medicine(self, topic_or_concept: str) -> Dict[str, Any]:
        """استرجاع المراجع والمفاهيم التراثية والروحانية المرتبطة بالاستعلام"""
        query_lower = topic_or_concept.strip().lower()
        matched_treatises = {}
        matched_planes = {}

        for title, treatise in self.treatises.items():
            combined_text = f"{title} {treatise['author']} {treatise['category']} {treatise['core_thesis']} {' '.join(treatise['key_chapters'])} {treatise['academic_summary']}".lower()
            if not query_lower or query_lower in combined_text:
                matched_treatises[title] = treatise

        for plane_title, plane_data in self.planes_atlas.items():
            combined_plane = f"{plane_title} {plane_data['definition']} {' '.join(plane_data['key_concepts'])} {plane_data['historical_perspective']}".lower()
            if not query_lower or query_lower in combined_plane:
                matched_planes[plane_title] = plane_data

        return {
            "success": True,
            "query": topic_or_concept,
            "matched_treatises_count": len(matched_treatises),
            "treatises": matched_treatises if matched_treatises else self.treatises,
            "planes": matched_planes if matched_planes else self.planes_atlas,
            "scholars": self.healers,
            "safety_guardrail": {
                "nature": "Academic, Philosophical & Spiritual Heritage",
                "disclaimer": "المعلومات المستعرضة تمثل التراث الفلسفي والروحاني وتاريخ الطب النفسي الإنساني، وتهدف إلى تزكية الفكر والتأمل وتوازن الروح، ولا تعد بديلاً عن الطب السريري العضوي عند وجود أمراض جسدية."
            }
        }

    def get_planes_atlas(self) -> Dict[str, Any]:
        """جلب خارطة العوالم العلوية والمثالية والسفلية بالكامل"""
        return {
            "success": True,
            "planes": self.planes_atlas,
            "disclaimer": "دراسة أنطولوجية مقارنة في فلسفة الوجود وميتافيزيقا الحضارات."
        }

esoteric_engine = NeamaEsotericEngine()
